/**
 * One-command setup: creates server/.env with strong random secrets (if it
 * does not exist yet) and creates/updates the database.
 *
 *   npm run setup
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const envPath = path.join(root, '.env');

if (fs.existsSync(envPath)) {
  console.log('✔ server/.env already exists — keeping your existing secrets.');
} else {
  const env = [
    '# Generated by `npm run setup`. Never commit this file.',
    'NODE_ENV=development',
    'API_PORT=4000',
    'CLIENT_URL=http://localhost:5173',
    'DATABASE_URL="file:./dev.db"',
    `JWT_SECRET=${crypto.randomBytes(48).toString('base64url')}`,
    `ENCRYPTION_KEY=${crypto.randomBytes(32).toString('base64')}`,
    '',
    '# Optional: real email delivery. Leave blank to use the built-in dev mailbox.',
    'SMTP_HOST=',
    'SMTP_PORT=587',
    'SMTP_USER=',
    'SMTP_PASS=',
    'MAIL_FROM="Digital Legacy Manager <no-reply@example.com>"',
    '',
  ].join('\n');
  fs.writeFileSync(envPath, env, { mode: 0o600 });
  console.log('✔ Created server/.env with fresh random secrets.');
}

console.log('… Preparing the database');
execSync('npx prisma migrate deploy', { cwd: root, stdio: 'inherit' });
execSync('npx prisma generate', { cwd: root, stdio: 'inherit' });
console.log('\n✔ Setup complete. Run "npm run seed" for demo data, then "npm run dev".');
